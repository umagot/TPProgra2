public class PerfilUsuario {
    int id;
    String nombre;
    String especialidad;
    String mail;
    String habilidades;




    public PerfilUsuario(int id, String nombre, String especialidad, String mail, String habilidades) {
        this.id = id;
        this.nombre = nombre;
        this.especialidad = especialidad;
        this.mail = mail;
        this.habilidades = habilidades;


    }
}